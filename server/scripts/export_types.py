"""Generate web/src/types.gen.ts from the Pydantic models in schemas.py. Run after changing a shape."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "server"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from wish_broker.schemas import API_MODELS  # noqa: E402

_, schema = models_json_schema([(m, "serialization") for m in API_MODELS], ref_template="#/$defs/{model}")
# Drop per-field titles; otherwise json2ts emits an alias type for every field.
for d in schema["$defs"].values():
    for prop in d.get("properties", {}).values():
        prop.pop("title", None)
# A root object that references every model, so json2ts emits them all as named types.
schema.update({"title": "Api", "type": "object", "additionalProperties": False,
               "properties": {m.__name__: {"$ref": f"#/$defs/{m.__name__}"} for m in API_MODELS}})
tmp = ROOT / "web" / "node_modules" / ".api-schema.json"
tmp.write_text(json.dumps(schema))
out = subprocess.run(["npx", "--no-install", "json2ts", "-i", str(tmp), "--bannerComment",
                      "/* Generated by server/scripts/export_types.py from schemas.py. Do not edit. */",
                      "--unreachableDefinitions", "--additionalProperties", "false"],
                     cwd=ROOT / "web", capture_output=True, text=True, check=True).stdout
(ROOT / "web" / "src").mkdir(exist_ok=True)
(ROOT / "web" / "src" / "types.gen.ts").write_text(out)
print("wrote web/src/types.gen.ts")
